/**
 * ════════════════════════════════════════════════════════════════════
 * FEATURE 8 — next/image: priority, sizes, placeholder="blur"
 * ════════════════════════════════════════════════════════════════════
 *
 * WHAT IT IS
 * ----------
 * Three underused props on Next.js <Image>:
 *
 * priority        — preloads image in <head> → improves LCP score
 * sizes           — tells browser which image size to download at each
 *                   viewport → 50-80% bandwidth savings on mobile
 * placeholder="blur" + blurDataURL — shows a tiny blurred preview
 *                   while the full image loads → eliminates CLS
 *
 * WHAT WE CURRENTLY USE INSTEAD
 * ------------------------------
 * From InvestorAccountSettingsPage.tsx + team-logo.ts (real code):
 *
 *   <Image
 *     src={user.avatarUrl}
 *     alt={user.name}
 *     width={80}
 *     height={80}
 *     // Missing: priority (above-fold avatar)
 *     // Missing: sizes (always downloads 80px variant from CDN)
 *     // Missing: placeholder (blank space while loading → CLS)
 *   />
 *
 * HOW THESE PROPS IMPROVE THINGS
 * ---------------------------------
 * priority:
 *   - Adds <link rel="preload"> in <head> for the image
 *   - Google PageSpeed LCP improvement: typically 200-500ms faster
 *   - Rule: use on the largest image visible without scrolling
 *
 * sizes:
 *   - Next.js generates srcSet variants (640w, 750w, 828w, 1080w…)
 *   - WITHOUT sizes: browser picks the largest variant to be safe
 *   - WITH sizes="80px": browser picks the smallest fitting variant
 *   - On a 390px mobile screen, an 80px avatar downloads 80px not 1080px
 *
 * placeholder="blur":
 *   - Shows a 10x10px blurred LQIP while full image loads
 *   - Zero layout shift (CLS = 0) because space is always reserved
 *   - blurDataURL can come from your CDN or be generated at build time
 *
 * REAL BETSIGNAL USE-CASES
 * -------------------------
 * • User avatar on Account Settings — priority + sizes="80px"
 * • Team logos on Sports pages — sizes="(max-width: 768px) 32px, 48px"
 * • Sport hero banners — priority + fill + placeholder="blur"
 * • OG images in layout.tsx — already using getImageProps ✓
 * • Country flags (country-flag-icons) — sizes="20px"
 *
 * HOW IT IMPACTS THE PROJECT
 * ---------------------------
 * - LCP improvement: measurable 200-500ms on avatar/hero images
 * - Bandwidth: 60-80% reduction on mobile for fixed-size images
 * - CLS: eliminates layout shift for all known-dimension images
 * - Directly improves Core Web Vitals / Google PageSpeed scores
 * ════════════════════════════════════════════════════════════════════
 */

